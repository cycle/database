<?php

declare(strict_types=1);

namespace Cycle\Database\Tests\Feature\SQLite\Query;

use Cycle\Database\Driver\SQLite\Query\SQLiteInsertQuery;
use Cycle\Database\Exception\BuilderException;
use Cycle\Database\Injection\Fragment;
use Cycle\Database\Tests\Feature\Common\Query\InsertQueryTest as CommonClass;
use Cycle\Testing\Database\Assert\SqlAssert;
use Testo\Assert;
use Testo\Expect;
use Testo\Test;

final class InsertQueryTest extends CommonClass
{
    #[Test]
    public function testQueryInstance(): void
    {
        parent::testQueryInstance();
        Assert::instanceOf($this->database->insert(), SQLiteInsertQuery::class);
    }

    #[Test]
    public function testCustomReturning(): void
    {
        $insert = $this->database->insert()->into('table')
            ->columns('name', 'balance')
            ->values('Anton', 100)
            ->returning('name');

        SqlAssert::same($insert, 'INSERT INTO {table} ({name}, {balance}) VALUES (?, ?) RETURNING {name}');
    }

    #[Test]
    public function testCustomMultipleReturning(): void
    {
        $insert = $this->database->insert()->into('table')
            ->columns('name', 'balance')
            ->values('Anton', 100)
            ->returning('name', 'created_at');

        SqlAssert::same($insert, 'INSERT INTO {table} ({name}, {balance}) VALUES (?, ?) RETURNING {name}, {created_at}');
    }

    #[Test]
    public function testCustomReturningWithFragment(): void
    {
        $insert = $this->database->insert()->into('table')
            ->columns('name', 'balance')
            ->values('Anton', 100)
            ->returning(new Fragment('"name" as "full_name"'));

        SqlAssert::same($insert, 'INSERT INTO {table} ({name}, {balance}) VALUES (?, ?) RETURNING {name} as {full_name}');
    }

    #[Test]
    public function testReturningWithoutColumnsShouldThrowAnException(): void
    {
        Expect::exception(BuilderException::class)->withMessageContaining('RETURNING clause should contain at least 1 column.');

        $this->database->insert()->into('table')
            ->columns('name', 'balance')
            ->values('Anton', 100)
            ->returning();
    }

    #[Test]
    public function testReturningSingleValueFromDatabase(): void
    {
        $schema = $this->schema('returning_value');
        $schema->primary('id');
        $schema->string('name');
        $schema->save();

        $returning = $this->database
            ->insert('returning_value')
            ->values(['name' => 'foo'])
            ->returning('id')
            ->run();

        Assert::same($returning, 1);
    }

    #[Test]
    public function testReturningValuesFromDatabase(): void
    {
        $schema = $this->schema('returning_values');
        $schema->primary('id');
        $schema->string('name');
        $schema->save();

        $returning = $this->database
            ->insert('returning_values')
            ->values(['name' => 'foo'])
            ->returning('id', 'name')
            ->run();

        Assert::same($returning['id'], 1);
        Assert::same($returning['name'], 'foo');

        $returning = $this->database
            ->insert('returning_values')
            ->values(['name' => 'bar'])
            ->returning('id', new Fragment('"name" as "title"'))
            ->run();

        Assert::same($returning['id'], 2);
        Assert::same($returning['title'], 'bar');
    }

    /**
     * A part of a composite key generated by the database can only be read back via RETURNING:
     * the `lastInsertId` fallback is limited to single-column keys.
     */
    #[Test]
    public function testReturningGeneratedPartOfCompositeKey(): void
    {
        $this->database->execute(
            <<<'SQL'
                CREATE TABLE composite_key (
                    parent_id varchar(36) NOT NULL,
                    id        integer     NOT NULL PRIMARY KEY AUTOINCREMENT,
                    UNIQUE (parent_id, id)
                )
                SQL,
        );

        $id = $this->database
            ->insert('composite_key')
            ->values(['parent_id' => 'parent'])
            ->returning('id')
            ->run();

        Assert::same($id, 1);
    }

    #[Test]
    public function testSimpleInsertMultipleRows(): void
    {
        $insert = $this->database->insert()->into('table')
            ->columns('name', 'balance')
            ->values('Anton', 100)
            ->values('John', 200);

        SqlAssert::same($insert, 'INSERT INTO {table} ({name}, {balance}) SELECT ? AS {name}, ? AS {balance}
UNION ALL SELECT ?, ?');
    }

    #[Test]
    public function testInsertMultipleRowsAsArray(): void
    {
        $insert = $this->database->insert()->into('table')->values([
            ['name' => 'Anton', 'balance' => 100],
            ['name' => 'John', 'balance' => 200],
        ]);

        SqlAssert::same($insert, 'INSERT INTO {table} ({name}, {balance}) SELECT ? AS {name}, ? AS {balance}
UNION ALL SELECT ?, ?');
    }

    #[Test]
    public function testSimpleInsertMultipleRows2(): void
    {
        $insert = $this->database->insert()->into('table')
            ->columns('name', 'balance')
            ->values('Anton', 100)
            ->values('John', 200)
            ->values('Pitt', 200);

        SqlAssert::same($insert, 'INSERT INTO {table} ({name}, {balance}) SELECT ? AS {name}, ? AS {balance}'
        . ' UNION ALL SELECT ?, ?'
        . ' UNION ALL SELECT ?, ?');
    }

    #[Test]
    public function testInsertMicroseconds(): void
    {
        $schema = $this->schema(
            table: 'with_microseconds',
            driverConfig: ['options' => ['withDatetimeMicroseconds' => true]],
        );
        $schema->primary('id');
        $schema->datetime('datetime', 6);
        $schema->save();

        $expected = new \DateTimeImmutable();

        $id = $this->db(
            driverConfig: ['options' => ['withDatetimeMicroseconds' => true]],
        )->insert('with_microseconds')->values([
            'datetime' => $expected,
        ])->run();

        $result = $this->db(
            driverConfig: ['options' => ['withDatetimeMicroseconds' => true]],
        )->select('datetime')
            ->from('with_microseconds')
            ->where('id', $id)
            ->run()
            ->fetch();

        Assert::same($result['datetime'], $expected->setTimezone($this->database->getDriver()->getTimezone())->format('Y-m-d H:i:s.u'));
    }

    #[Test]
    public function testInsertDatetimeWithoutMicroseconds(): void
    {
        $schema = $this->schema('without_microseconds');
        $schema->primary('id');
        $schema->datetime('datetime');
        $schema->save();

        $expected = new \DateTimeImmutable();

        $id = $this->database->insert('without_microseconds')->values([
            'datetime' => $expected,
        ])->run();

        $result = $this->database->select('datetime')
            ->from('without_microseconds')
            ->where('id', $id)
            ->run()
            ->fetch();

        Assert::same($result['datetime'], $expected->setTimezone($this->database->getDriver()->getTimezone())->format('Y-m-d H:i:s'));
    }
}
